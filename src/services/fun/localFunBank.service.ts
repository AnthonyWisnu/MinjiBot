export class LocalFunBankService {
  pickRandom(category: LocalFunCategory, indexOverride?: number): { title: string; text: string } {
    const bank = LOCAL_FUN_BANKS[category];
    const len = bank.entries.length;
    const idx =
      indexOverride !== undefined
        ? Math.abs(Math.floor(indexOverride)) % len
        : randomInt(0, len);
    const text = bank.entries[idx] ?? bank.entries[0] ?? "";
    return {
      title: bank.title,
      text,
    };
  }
}

